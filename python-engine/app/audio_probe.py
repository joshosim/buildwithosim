"""Validate an uploaded file before any expensive work happens.

Two checks, in order:

1. A magic-byte check. Extensions and client-supplied content types are
   attacker-controlled, and ffmpeg will happily open text "playlist" formats
   (HLS, concat) that reference other files or URLs. Requiring a real audio
   container signature rules those out before ffmpeg ever sees the file.
2. ``ffprobe``, restricted to the ``file`` protocol, to confirm there is an
   audio stream and to read its duration. The duration cap matters: a heavily
   compressed file can be small on disk and enormous once decoded.
"""

from __future__ import annotations

import json
import shutil
import subprocess
from dataclasses import dataclass
from pathlib import Path

from .errors import EngineHTTPError

HEAD_BYTES = 16


@dataclass(frozen=True)
class AudioInfo:
    duration_seconds: float
    codec: str | None


def ffmpeg_available() -> bool:
    return shutil.which("ffprobe") is not None and shutil.which("ffmpeg") is not None


def looks_like_audio_container(head: bytes) -> bool:
    """True when ``head`` starts like one of the container formats we accept."""
    if len(head) < 4:
        return False
    if head.startswith(b"ID3"):  # MP3 with an ID3v2 tag
        return True
    if head[0] == 0xFF and (head[1] & 0xE0) == 0xE0:  # MPEG audio / ADTS AAC frame sync
        return True
    if head.startswith(b"RIFF") and head[8:12] == b"WAVE":
        return True
    if head.startswith(b"fLaC"):
        return True
    if head.startswith(b"OggS"):  # Ogg Vorbis and Opus
        return True
    if head.startswith(b"FORM") and head[8:12] in (b"AIFF", b"AIFC"):
        return True
    if head[4:8] == b"ftyp":  # MP4 / M4A
        return True
    return False


def read_head(path: Path) -> bytes:
    with path.open("rb") as handle:
        return handle.read(HEAD_BYTES)


def _duration_seconds(data: dict, audio_streams: list[dict]) -> float | None:
    candidates = [data.get("format", {}).get("duration")]
    candidates += [stream.get("duration") for stream in audio_streams]
    for raw in candidates:
        try:
            value = float(raw)
        except (TypeError, ValueError):
            continue
        if value > 0:
            return value
    return None


def probe_audio(path: Path, *, timeout: float = 20.0) -> AudioInfo:
    """Return basic info about ``path`` or raise an :class:`EngineHTTPError`."""
    if not looks_like_audio_container(read_head(path)):
        raise EngineHTTPError(
            422,
            "unrecognized_audio",
            "That file doesn't look like a supported audio file, even though its name ends in an audio extension.",
        )

    ffprobe = shutil.which("ffprobe")
    if ffprobe is None:
        raise EngineHTTPError(
            503,
            "ffmpeg_missing",
            "The separation engine is missing ffmpeg, so it can't read audio files right now.",
        )

    try:
        result = subprocess.run(  # noqa: S603 - fixed argv, no shell, path is generated by us
            [
                ffprobe,
                "-v",
                "error",
                "-protocol_whitelist",
                "file",
                "-print_format",
                "json",
                "-show_format",
                "-show_streams",
                str(path),
            ],
            capture_output=True,
            timeout=timeout,
            check=False,
        )
    except subprocess.TimeoutExpired:
        raise EngineHTTPError(422, "unreadable_audio", "Reading that file took too long. It may be corrupt.") from None

    if result.returncode != 0:
        raise EngineHTTPError(
            422,
            "unreadable_audio",
            "That file couldn't be read as audio. It may be corrupt or incomplete.",
        )

    try:
        data = json.loads(result.stdout or b"{}")
    except json.JSONDecodeError:
        raise EngineHTTPError(422, "unreadable_audio", "That file couldn't be read as audio.") from None

    audio_streams = [s for s in data.get("streams", []) if s.get("codec_type") == "audio"]
    if not audio_streams:
        raise EngineHTTPError(422, "no_audio_stream", "No audio track was found in that file.")

    duration = _duration_seconds(data, audio_streams)
    if duration is None:
        raise EngineHTTPError(
            422,
            "duration_unknown",
            "Couldn't determine how long that track is, so it can't be checked against the length limit.",
        )

    return AudioInfo(duration_seconds=duration, codec=audio_streams[0].get("codec_name"))
